def _write_text(path: str, content: str) -> bool:
    """内容相同则不写；返回是否发生写入。"""
    if os.path.isfile(path):
        with open(path, 'r', encoding='utf-8') as handle:
            if handle.read() == content:
                return False
    with open(path, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(content)
    return True


def _check_text(path: str, content: str) -> bool:
    if not os.path.isfile(path):
        return False
    with open(path, 'r', encoding='utf-8') as handle:
        return handle.read() == content


def write_schema() -> bool:
    return _write_text(SCHEMA_PATH, render_schema())


def check_schema() -> bool:
    return _check_text(SCHEMA_PATH, render_schema())


