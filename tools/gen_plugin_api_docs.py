def _replace_generated_region(text: str, begin: str, end: str, body: str, *, label: str) -> str:
    """把 text 中 `begin…end` marker 之间的内容替换为 body（marker 行保留）。"""
    start = text.find(begin)
    if start < 0:
        raise RuntimeError(f'{label} 缺少生成区起始标记: {begin}')
    stop = text.find(end, start + len(begin))
    if stop < 0:
        raise RuntimeError(f'{label} 缺少生成区结束标记: {end}')
    head = text[:start + len(begin)]
    tail = text[stop:]
    return f'{head}\n{body.rstrip()}\n{tail}'


def render_checker(current: str | None = None) -> str:
    """按当前 `contract.py` / 宿主事实重算 `stm_plugin_check.py` 全文。"""
    if current is None:
        if not os.path.isfile(CHECKER_PATH):
            raise RuntimeError(
                'tools/stm_plugin_check.py 不存在：该文件是手写主体 + 生成区的单文件 CLI'
            )
        with open(CHECKER_PATH, 'r', encoding='utf-8') as handle:
            current = handle.read()
    text = _replace_generated_region(
        current, CHECKER_CONTRACT_BEGIN, CHECKER_CONTRACT_END,
        _contract_source(), label='tools/stm_plugin_check.py',
    )
    return _replace_generated_region(
        text, CHECKER_HOST_BEGIN, CHECKER_HOST_END,
        _host_facts_body(), label='tools/stm_plugin_check.py',
    )


def write_checker() -> bool:
    """写入 CLI 脚本页面；内容无变化时返回 False。"""
    with open(CHECKER_PATH, 'r', encoding='utf-8') as handle:
        current = handle.read()
    content = render_checker(current)
    if content == current:
        return False
    with open(CHECKER_PATH, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(content)
    return True


def check_checker() -> bool:
    """`stm_plugin_check.py` 的生成区是否与契约/宿主事实同步。"""
    if not os.path.isfile(CHECKER_PATH):
        return False
    with open(CHECKER_PATH, 'r', encoding='utf-8') as handle:
        current = handle.read()
    try:
        return current == render_checker(current)
    except RuntimeError:
        return False


