def _first_doc_line(obj) -> str:
    doc = (getattr(obj, '__doc__', '') or '').strip()
    if not doc:
        return ''
    return doc.splitlines()[0].strip()


def _format_signature(name: str, func) -> str:
    try:
        signature = inspect.signature(func)
    except (TypeError, ValueError):
        return f'{name}(…)'

    # 去掉 self / cls：插件作者看到的是「调用形态」
    parameters = list(signature.parameters.values())
    if parameters and parameters[0].name in ('self', 'cls'):
        signature = signature.replace(parameters=parameters[1:])
    return f'{name}{signature}'


def collect_backend_api() -> dict:
    """返回 `{'attributes': [...], 'groups': [...], 'internal': [...], 'public': [...]}`。"""
    from core.plugins.api import PluginAPI

    public = sorted(
        name for name, member in inspect.getmembers(PluginAPI, predicate=inspect.isfunction)
        if not name.startswith('_')
    )

    declared = set(BACKEND_INTERNAL)
    groups = []
    for title, default_stability, methods in BACKEND_GROUPS:
        rows = []
        for entry in methods:
            if isinstance(entry, tuple):
                name, stability = entry
            else:
                name, stability = entry, default_stability
            func = getattr(PluginAPI, name, None)
            if func is None:
                continue
            declared.add(name)
            rows.append({
                'name': name,
                'signature': _format_signature(name, func),
                'stability': stability,
                'doc': _first_doc_line(func),
            })
        groups.append({'title': title, 'stability': default_stability, 'rows': rows})

    return {
        'attributes': list(BACKEND_ATTRIBUTES),
        'groups': groups,
        'internal': list(BACKEND_INTERNAL),
        'public': public,
        'declared': sorted(declared),
    }


def collect_frontend_members() -> list:
    """解析 `pluginHost.js` 里 `buildApi()` 返回对象的顶层键。"""
    with open(HOST_PATH, 'r', encoding='utf-8') as handle:
        source = handle.read()

    start = source.find('buildApi(entry, manifest) {')
    if start < 0:
        raise RuntimeError('pluginHost.js 中未找到 buildApi()')

    end = source.find('\n  }', start)
    body = source[start:end if end > 0 else len(source)]

    keys = []
    for line in body.splitlines():
        match = re.match(
            r'^      (?:(?:async|get|set)\s+)?([a-zA-Z][a-zA-Z0-9_]*)\s*[:(,]',
            line,
        )
        if not match:
            continue
        key = match.group(1)
        if key not in keys and key not in ('const', 'return', 'if', 'for'):
            keys.append(key)
    return keys


