def write_document() -> bool:
    """写入文档；内容无变化时返回 False。"""
    content = render()
    if os.path.isfile(DOC_PATH):
        with open(DOC_PATH, 'r', encoding='utf-8') as handle:
            if handle.read() == content:
                return False
    with open(DOC_PATH, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(content)
    return True


def check_document() -> bool:
    """文档是否与当前代码一致。"""
    if not os.path.isfile(DOC_PATH):
        return False
    with open(DOC_PATH, 'r', encoding='utf-8') as handle:
        return handle.read() == render()


def collect_source_defined_methods() -> list:
    """用 AST 静态列出 `PluginAPI` 的所有公开方法（不 import，便于对照）。"""
    with open(API_PATH, 'r', encoding='utf-8') as handle:
        tree = ast.parse(handle.read())

    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == 'PluginAPI':
            return sorted(
                item.name for item in node.body
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
                and not item.name.startswith('_')
            )
    raise RuntimeError('api.py 中未找到 PluginAPI')


def _configure_stdout() -> None:
    """Windows 控制台默认 GBK，直接打印非 ASCII 会抛 UnicodeEncodeError。"""
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except (AttributeError, OSError, ValueError):
        pass


def main(argv=None) -> int:
    _configure_stdout()
    parser = argparse.ArgumentParser(description='生成插件 API 参考文档')
    parser.add_argument('--check', action='store_true', help='只校验，不写文件')
    args = parser.parse_args(argv)

    if args.check:
        if check_document():
            print('✅ docs/plugin-api.md 已是最新')
            return 0
        print('❌ docs/plugin-api.md 与代码不一致，请运行 python tools/gen_plugin_api_docs.py')
        return 1

    changed = write_document()
    print('✅ 已生成 docs/plugin-api.md' if changed else '✅ docs/plugin-api.md 无变化')
    return 0


if __name__ == '__main__':
    sys.exit(main())
