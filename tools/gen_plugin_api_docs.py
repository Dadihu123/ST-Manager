def _md_table(headers, rows) -> list:
    """渲染 markdown 表格（单元格里的竖线由调用方负责转义）。"""
    lines = [
        '| ' + ' | '.join(headers) + ' |',
        '|' + '|'.join('---' for _ in headers) + '|',
    ]
    for row in rows:
        lines.append('| ' + ' | '.join(str(cell) for cell in row) + ' |')
    return lines


