def collect_source_defined_methods() -> list:
    """用 AST 静态列出 `PluginAPI` 的所有公开方法（不 import，便于对照）。"""
    with open(API_PATH, 'r', encoding='utf-8') as handle:
        tree = ast.parse(handle.read())

    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == 'PluginAPI':
            return sorted(
                item.name for item in node.body
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
                and not item.name.startswith('_')
            )
    raise RuntimeError('api.py 中未找到 PluginAPI')


def _configure_stdout() -> None:
    """Windows 控制台默认 GBK，直接打印非 ASCII 会抛 UnicodeEncodeError。"""
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except (AttributeError, OSError, ValueError):
        pass


def main(argv=None) -> int:
    _configure_stdout()
    parser = argparse.ArgumentParser(description='生成插件 API 参考文档、manifest schema 与前端类型')
    parser.add_argument('--check', action='store_true', help='只校验，不写文件')
    args = parser.parse_args(argv)

    # 每项：展示名、检查函数、生成函数
    artifacts = [
        ('docs/plugin-api.md', check_document, write_document),
        ('docs/plugin-manifest.schema.json', check_schema, write_schema),
        ('docs/plugin-api.d.ts', check_dts, write_dts),
        ('tools/stm_plugin_check.py', check_checker, write_checker),
    ]

    if args.check:
        stale = []
        for label, check, _write in artifacts:
            if check():
                print(f'✅ {label} 已是最新')
            else:
                print(f'❌ {label} 与来源不一致，请运行 python tools/gen_plugin_api_docs.py')
                stale.append(label)
        return 0 if not stale else 1

    for label, _check, write in artifacts:
        changed = write()
        print(f'✅ 已生成 {label}' if changed else f'✅ {label} 无变化')
    return 0


if __name__ == '__main__':
    sys.exit(main())
