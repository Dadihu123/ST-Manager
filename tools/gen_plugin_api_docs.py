    properties = _menu_common_properties(with_placement=with_placement)
    required = ['id', 'type']
    if with_placement:
        required.insert(1, 'placement')
    if node_type == 'item':
        properties['action'] = {'$ref': '#/$defs/action'}
        required.extend(['label', 'action'])
    elif node_type == 'submenu':
        properties['children'] = _array(
            {'oneOf': [_ref(name) for name in child_variants]},
            min_items=1,
            description=f'子节点；整棵树最多 {contract.MAX_MENU_DEPTH} 层（含根节点）',
        )
