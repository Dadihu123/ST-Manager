def _ref(name: str) -> dict:
    return {'$ref': f'#/$defs/{name}'}


def _x_pattern_properties() -> dict:
    return {'^x-': {'description': '实验键（`x-` 前缀）：宿主静默忽略（设计 §4.9）'}}


def _object(properties, *, required=(), description='', allow_experimental=True) -> dict:
    schema = {}
    if description:
        schema['description'] = description
    schema['type'] = 'object'
    schema['properties'] = properties
    if required:
        schema['required'] = list(required)
    schema['additionalProperties'] = False
    if allow_experimental:
        schema['patternProperties'] = _x_pattern_properties()
    return schema


def _array(items, *, min_items=None, max_items=None, description='', unique=False) -> dict:
    schema = {}
    if description:
        schema['description'] = description
    schema['type'] = 'array'
    if min_items is not None:
        schema['minItems'] = min_items
    if max_items is not None:
        schema['maxItems'] = max_items
    if unique:
        schema['uniqueItems'] = True
    schema['items'] = items
    return schema


